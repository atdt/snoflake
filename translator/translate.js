// Translates the SIL source code into JavaScript.
// The PEG grammar parses source-level SIL into the assembler listing, then
// assembly emits a runtime image with resolved symbols, initialized memory,
// and executable instructions.
import peggy from 'peggy';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';
// Import directly from the SIL modules rather than the public entry: the
// public entry imports the generated snobol.sil.js, which is the file we are
// about to overwrite.
import '../src/SNOBOL/mem.js';
import '../src/SNOBOL/vm.js';
import { assemble } from '../src/SNOBOL/assemble.js';

function indent( text, spaces ) {
    const prefix = ' '.repeat( spaces );
    return text.split( '\n' ).map( line => prefix + line ).join( '\n' );
}

// One instruction per line preserves the SIL-listing feel of the
// instruction section: each line reads as a resolved macro call.
function serializeInstructions( instructions ) {
    return instructions
        .map( stmt => '    ' + JSON.stringify( stmt ) )
        .join( ',\n' );
}

// The memory snapshot is the assembled byte image. Wrap to fit a typical
// editor window without producing one giant unreadable line.
function serializeMemory( memory ) {
    const cellsPerLine = 16,
          lines = [];
    for ( let i = 0; i < memory.length; i += cellsPerLine ) {
        const chunk = Array.from( memory.subarray( i, i + cellsPerLine ) );
        lines.push( '    ' + chunk.join( ',' ) );
    }
    return lines.join( ',\n' );
}

function serializeImage( image ) {
    return [
        'export default {',
        '  "symbols": ' + indent( JSON.stringify( image.symbols, null, 2 ), 2 ).trimStart() + ',',
        '  "memory": new Uint32Array([',
        serializeMemory( image.memory ),
        '  ]),',
        '  "instructions": [',
        serializeInstructions( image.instructions ),
        '  ]',
        '};',
        ''
    ].join( '\n' );
}

const __dirname = dirname( fileURLToPath( import.meta.url ) );
const invokedPath = fileURLToPath( import.meta.url );

if ( process.argv[ 1 ] === invokedPath ) {
    const source = __dirname + '/../external/v311-snoflake.sil',
          grammar = fs.readFileSync( __dirname + '/sil.peg' ).toString( 'utf-8' ),
          snobol = fs.readFileSync( source ).toString( 'utf-8' ),
          listing = peggy.generate( grammar ).parse( snobol ),
          prolog = [
              '// This file was automatically generated by translator/translate.js.',
              '// Source: external/v311-snoflake.sil',
              '// Image sections: resolved symbols, data declarations, and resolved instructions.',
              ''
          ].join( '\n' ),
          image = assemble( listing ),
          code = prolog + serializeImage( image );

    process.stdout.write( code );
}
