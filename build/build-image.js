// Translate SIL source into the JavaScript runtime image.
import peggy from 'peggy';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

// The public entry imports the generated image this script overwrites.
import { assemble } from '../src/assemble.js';

const __dirname = path.dirname( fileURLToPath( import.meta.url ) );
const sourcePath = path.join( __dirname, '..', 'external', 'v311-snoflake.sil' );
const grammarPath = path.join( __dirname, 'sil-grammar.peg' );

const listing = parseSource();
const image = assemble( listing );
const code = generatedFileProlog() + serializeImage( image );

process.stdout.write( code );

function parseSource() {
    const grammar = fs.readFileSync( grammarPath, 'utf8' );
    const source = fs.readFileSync( sourcePath, 'utf8' );

    return peggy.generate( grammar ).parse( source );
}

function generatedFileProlog() {
    return [
        '// This file was automatically generated by build/build-image.js.',
        '// Source: external/v311-snoflake.sil',
        '// Image sections: resolved symbols, data declarations, and resolved instructions.',
        ''
    ].join( '\n' );
}

function serializeImage( image ) {
    return [
        'export default {',
        '  "symbols": ' + serializeSymbols( image.symbols ) + ',',
        '  "memory": new Uint32Array([',
        serializeMemory( image.memory ),
        '  ]),',
        '  "instructions": [',
        serializeInstructions( image.instructions ),
        '  ]',
        '};',
        ''
    ].join( '\n' );
}

function serializeSymbols( symbols ) {
    return JSON.stringify( symbols, null, 2 )
        .split( '\n' )
        .map( line => '  ' + line )
        .join( '\n' )
        .trimStart();
}

function serializeMemory( memory ) {
    const cellsPerLine = 16;
    const lines = [];

    for ( let i = 0; i < memory.length; i += cellsPerLine ) {
        const chunk = Array.from( memory.subarray( i, i + cellsPerLine ) );
        lines.push( '    ' + chunk.join( ',' ) );
    }

    return lines.join( ',\n' );
}

function serializeInstructions( instructions ) {
    return instructions
        .map( stmt => '    ' + JSON.stringify( stmt ) )
        .join( ',\n' );
}
